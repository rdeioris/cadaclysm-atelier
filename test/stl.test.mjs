import assert from "node:assert/strict";
import { parseStl } from "../stl.js";
const ascii = "solid t\nfacet normal 0 0 1\nouter loop\nvertex 0 0 0\nvertex 2 0 0\nvertex 0 3 1\nendloop\nendfacet\nendsolid t\n";
const a = parseStl(new TextEncoder().encode(ascii));
assert.deepEqual(a.bounds, [0, 0, 0, 2, 3, 1]);
assert.equal(a.indices.length, 3);
const bin = new Uint8Array(84 + 50); const dv = new DataView(bin.buffer);
dv.setUint32(80, 1, true);
[0, 0, 0, 2, 0, 0, 0, 3, 1].forEach((v, i) => dv.setFloat32(96 + 4 * i, v, true));
assert.deepEqual(parseStl(bin).bounds, [0, 0, 0, 2, 3, 1]);
assert.throws(() => parseStl(new Uint8Array([1, 2, 3])));
console.log("stl: ok");
